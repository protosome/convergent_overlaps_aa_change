# Add symmetric entries for the ProtSub matrix
for (aa1, aa2), score in list(prot_sub_matrix.items()):
    prot_sub_matrix[(aa2, aa1)] = score

# Define the function to calculate ProtSub similarity
def calculate_protsub_similarity(seq1, seq2, matrix=prot_sub_matrix):
    if len(seq1) != len(seq2):
        raise ValueError("Sequences must be of the same length")
    
    similarity_score = 0
    for aa1, aa2 in zip(seq1, seq2):
        score = matrix.get((aa1, aa2), matrix.get((aa2, aa1), -4))  # Use -4 as a default for unknown pairs
        similarity_score += score
    
    return similarity_score
